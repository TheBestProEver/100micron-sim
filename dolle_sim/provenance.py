def as_markdown(counts: dict | None = None) -> str:
    def md(s):
        return s.replace("*", "\\*").replace("<b>", "**").replace("</b>", "**").replace("|", "\\|")
    out = ["# Provenance: where every part of DOLL-E comes from", "",
           "Generated from `dolle_sim/provenance.py` (do not edit by hand; run `python tools/build_site.py`).",
           ""]
    out += [md(p) + "\n" for p in summary(counts)]
    out += ["**Origin key:** *published*: equation or value from the cited paper · *standard*: textbook "
            "physics or numerics · *derived*: derived or adapted for DOLL-E from standard physics · "
            "*assumed*: a modelling choice or value we chose.", ""]
    for sec in SECTIONS:
        out += [f"## {sec['title']}", "",
                "| component | based on | how it is checked | assumptions and limits |", "|---|---|---|---|"]
        for c in sec["items"]:
            reb = "" if c["rebound"] == "none" else f" · REBOUND: {c['rebound']}"
            refs = f"<br>*{md(c['refs'])}*" if c["refs"] else ""
            chk = md(c["checked"]) + (f"<br>`verify`: {', '.join(c['checks'])}" if c["checks"] else "")
            out.append(f"| **{md(c['component'])}**<br>`{c['code']}` | *{c['origin']}*{reb}: {md(c['basis'])}{refs} "
                       f"| {chk} | {md(c['limits'])} |")
        out.append("")
    out += ["## How much the inputs matter", "", "| change (100 um grains) | effect on the 50% sticking speed |",
            "|---|---|"]
    out += [f"| {md(a)} | {md(b)} |" for a, b in SENSITIVITY]
    return "\n".join(out) + "\n"


def as_text() -> str:
    import textwrap
    out = []
    for p in summary():
        out += textwrap.wrap(p.replace("<b>", "").replace("</b>", ""), 100) + [""]
    for sec in SECTIONS:
        out += [sec["title"].upper(), "-" * len(sec["title"])]
        for c in sec["items"]:
            reb = "" if c["rebound"] == "none" else f", REBOUND: {c['rebound']}"
            out.append(f"* {c['component']}  [{c['origin']}{reb}]  {c['code']}")
            for label, key in (("based on", "basis"), ("source", "refs"), ("checked", "checked"),
                               ("limits", "limits")):
                if c[key]:
                    out += textwrap.wrap(f"{label}: {c[key]}", 100, initial_indent="    ",
                                         subsequent_indent="      ")
        out.append("")
    out += ["HOW MUCH THE INPUTS MATTER (100 um grains)", "------------------------------------------"]
    out += [f"* {a}: {b}" for a, b in SENSITIVITY]
    return "\n".join(out)
