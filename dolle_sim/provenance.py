def line_counts(root: Path | None = None) -> dict:
    """Lines of code in the package, and how many are in the only files that use REBOUND and LAMMPS."""
    root = Path(root) if root else Path(__file__).resolve().parent
    files = sorted(root.glob("*.py"))
    n = {f.name: len(f.read_text(encoding="utf-8").splitlines()) for f in files}
    return {"total": sum(n.values()), "rebound_check": n.get("rebound_check.py", 0),
            "lammps_check": n.get("lammps_check.py", 0), "files": len(files)}


def n_checks() -> int:
    """Number of automated verification checks (named in verification.py)."""
    import re
    src = (Path(__file__).resolve().parent / "verification.py").read_text(encoding="utf-8")
    return len(set(re.findall(r'_res\("(\w+)"', src)))


