"""Generate dolle_sim/atmosphere.py: air density vs altitude from NRLMSIS 2.1 (via pymsis).

    pip install pymsis
    python tools/make_atmosphere.py

NRLMSIS 2.1 is the U.S. Naval Research Laboratory's empirical model of the neutral atmosphere from the ground to
the exosphere (Emmert et al. 2021, Earth Space Sci. 8, e2020EA001321; 2.1: Emmert et al. 2022, JGR Space Phys.
127, e2022JA030896). pymsis (G. Lucas, LASP / SWx TREC, University of Colorado; MIT licence) wraps the official
Fortran code. The table is generated once so that the simulator (and the browser app) do not need pymsis.
"""
from __future__ import annotations

import datetime
from pathlib import Path

import numpy as np
import pymsis

ROOT = Path(__file__).resolve().parents[1]
LAT, LON = 37.94, -75.47           # the launch site
DATE = "2026-06-21T16:00"          # launch season (June), local midday
F107 = F107A = 150.0               # moderate solar activity (solar flux units)
AP = 4.0                           # quiet geomagnetic conditions
ALT_KM = np.arange(0.0, 251.0, 1.0)


def main():
    out = pymsis.calculate(np.datetime64(DATE), LON, LAT, ALT_KM, f107s=F107, f107as=F107A, aps=[[AP] * 7],
                           version=2.1)
    rho = out[..., pymsis.Variable.MASS_DENSITY].ravel()
    lines = [
        '"""Air density vs altitude (generated by tools/make_atmosphere.py; do not edit by hand).',
        "",
        f"NRLMSIS 2.1 (Emmert et al. 2021; 2022) via pymsis {pymsis.__version__}, for the launch site",
        f"({LAT} N, {-LON} W) on {DATE} UT with F10.7 = F10.7A = {F107:g} sfu and Ap = {AP:g}. Generated "
        f"{datetime.date.today().isoformat()}.",
        "Density varies with season, time of day and solar activity: by tens of percent below ~100 km and by",
        "factors of several above ~150 km. The flight model only needs it to order of magnitude.",
        "",
        "Provenance: NRLMSIS 2.1 output (published model, standard). No REBOUND code.",
        '"""',
        "from __future__ import annotations",
        "",
        "import math",
        "",
        "import numpy as np",
        "",
        f"ALT_KM = np.arange({ALT_KM[0]:g}, {ALT_KM[-1] + 1:g}, 1.0)",
        "LOG_RHO = np.array([",
    ]
    vals = [f"{np.log(r):.6f}" for r in rho]
    for i in range(0, len(vals), 10):
        lines.append("    " + ", ".join(vals[i:i + 10]) + ",")
    lines += [
        "])",
        "",
        "",
        "_L = [float(x) for x in LOG_RHO]",
        "",
        "",
        "def density(h_m: float) -> float:",
        '    """Air density [kg/m^3] at geometric altitude h_m [m] (log-linear interpolation on the 1 km grid; constant',
        '    scale height extrapolation above the table)."""',
        "    h = max(h_m / 1e3, 0.0)",
        "    n = len(_L) - 1",
        "    if h >= n:",
        "        return math.exp(_L[n] - (h - n) * (_L[n - 1] - _L[n]))",
        "    i = int(h)",
        "    return math.exp(_L[i] + (h - i) * (_L[i + 1] - _L[i]))",
        "",
    ]
    (ROOT / "dolle_sim" / "atmosphere.py").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote dolle_sim/atmosphere.py: rho(0) = {rho[0]:.4g}, rho(100 km) = {rho[100]:.3g}, "
          f"rho(200 km) = {rho[200]:.3g} kg/m^3")


if __name__ == "__main__":
    main()
