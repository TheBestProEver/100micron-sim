def line_counts(root: Path | None = None) -> dict:
    """Lines of code in the package, and how many are in the only file that uses REBOUND."""
    root = Path(root) if root else Path(__file__).resolve().parent
    files = sorted(root.glob("*.py"))
    n = {f.name: len(f.read_text(encoding="utf-8").splitlines()) for f in files}
    return {"total": sum(n.values()), "rebound_check": n.get("rebound_check.py", 0), "files": len(files)}


